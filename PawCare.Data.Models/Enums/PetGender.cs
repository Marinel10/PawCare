namespace PawCare.Data.Models.Enums
{
    
    /// <summary>
    /// Represents the biological sex of a pet.
    /// </summary>
    public enum PetGender
    {
        /// <summary>
        /// The pet's sex is unknown or has not been specified.
        /// </summary>
        Unknown = 0,

        /// <summary>
        /// The pet is male.
        /// </summary>
        Male = 1,

        /// <summary>
        /// The pet is female.
        /// </summary>
        Female = 2
    }
}
